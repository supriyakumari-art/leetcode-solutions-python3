class Solution:
    def findPeakElement(self, nums: List[int]) -> int:
        left =0
        right = len(nums)-1
        while(left < right):
            mid = left +(right-left+1)//2
            if nums[mid] < nums[mid-1]:
                right = mid - 1
            else:
                left = mid
        return left